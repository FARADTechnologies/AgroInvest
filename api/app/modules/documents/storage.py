"""File storage for application documents.

Files are kept in the database (table document_blob) under random names, never in the web
root; the original name is only stored with the document's metadata. The database is the one
durable store of a hosted deployment, so documents survive restarts and redeploys. The type is
decided from the file's first bytes, not from its extension, so a renamed executable is
rejected. Files written by older versions to UPLOAD_DIR are still read and are imported into
the database on start.
"""

import hashlib
import secrets
from dataclasses import dataclass
from pathlib import Path

from sqlalchemy import delete as sql_delete
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.config import get_settings
from app.core.errors import unprocessable
from app.modules.documents.models import ApplicationDocument, DocumentBlob

# Magic numbers of the accepted formats.
_SIGNATURES: list[tuple[bytes, str]] = [
    (b"%PDF-", "application/pdf"),
    (b"\xff\xd8\xff", "image/jpeg"),
    (b"\x89PNG\r\n\x1a\n", "image/png"),
]
_ZIP = b"PK\x03\x04"
_OOXML = {
    "word/": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
    "xl/": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
}

ACCEPTED_LABEL = "PDF, JPG, PNG, DOCX və ya XLSX"


@dataclass
class StoredFile:
    stored_name: str
    mime: str
    size: int
    sha256: str


def detect_mime(head: bytes) -> str | None:
    for signature, mime in _SIGNATURES:
        if head.startswith(signature):
            return mime
    if head.startswith(_ZIP):
        for marker, mime in _OOXML.items():
            if marker.encode() in head:
                return mime
    return None


def upload_dir() -> Path:
    path = get_settings().upload_dir
    path.mkdir(parents=True, exist_ok=True)
    return path


def save(session: AsyncSession, data: bytes, max_mb: int) -> StoredFile:
    if not data:
        raise unprocessable("empty_file", "Fayl boşdur")
    limit = min(max_mb, get_settings().max_upload_mb) * 1024 * 1024
    if len(data) > limit:
        raise unprocessable(
            "file_too_large", f"Faylın ölçüsü {limit // (1024 * 1024)} MB-dan çox olmamalıdır"
        )
    mime = detect_mime(data[:4096])
    if mime is None:
        raise unprocessable("file_type", f"Yalnız {ACCEPTED_LABEL} faylları qəbul olunur")
    name = secrets.token_hex(16)
    session.add(DocumentBlob(stored_name=name, data=data))
    return StoredFile(name, mime, len(data), hashlib.sha256(data).hexdigest())


def _legacy_path(stored_name: str) -> Path:
    # stored_name is generated by us (hex only); never derived from user input.
    return upload_dir() / stored_name


async def read(session: AsyncSession, stored_name: str) -> bytes | None:
    data = await session.scalar(
        select(DocumentBlob.data).where(DocumentBlob.stored_name == stored_name)
    )
    if data is not None:
        return data
    legacy = _legacy_path(stored_name)
    return legacy.read_bytes() if legacy.is_file() else None


async def delete(session: AsyncSession, stored_name: str) -> None:
    await session.execute(sql_delete(DocumentBlob).where(DocumentBlob.stored_name == stored_name))
    _legacy_path(stored_name).unlink(missing_ok=True)


async def import_legacy_files(session: AsyncSession) -> int:
    """Moves documents that older versions wrote to UPLOAD_DIR into the database."""
    if not get_settings().upload_dir.is_dir():
        return 0
    stored = select(DocumentBlob.stored_name)
    names = (
        await session.scalars(
            select(ApplicationDocument.stored_name).where(
                ApplicationDocument.stored_name.not_in(stored)
            )
        )
    ).all()
    moved = 0
    for name in names:
        path = _legacy_path(name)
        if path.is_file():
            session.add(DocumentBlob(stored_name=name, data=path.read_bytes()))
            moved += 1
    return moved
